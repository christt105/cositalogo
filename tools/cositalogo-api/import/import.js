const TITLE_COLUMNS = [
  "imdb", "title", "original_title", "english_title", "year", "tmdb_poster", "poster",
  "genres", "seasons", "season_posters", "detail", "json",
];
const LINK_COLUMNS = ["type", "tmdb_id", "season", "quality", "audio", "subs", "tags", "url"];

/** An SQL literal for a string, number or null. */
export function literal(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`cannot write ${value} as SQL`);
    return String(value);
  }
  return `'${String(value).replaceAll("'", "''")}'`;
}

const differs = (table, columns) => columns.map((c) => `${table}.${c} IS NOT excluded.${c}`).join(" OR ");

/** An insert that, on conflict, rewrites `columns` only when one of them differs, so a matching row costs no write. */
const upsert = (table, conflict, columns, row) =>
  `INSERT INTO ${table} (${Object.keys(row).join(", ")}) VALUES (${Object.values(row).map(literal).join(", ")}) ` +
  `ON CONFLICT (${conflict}) DO UPDATE SET ${[...columns, "updated_at"].map((c) => `${c} = excluded.${c}`).join(", ")} ` +
  `WHERE ${differs(table, columns)};`;

async function seasonInfo(tmdb, id, season) {
  try {
    const data = await tmdb.getTvSeason(id, season);
    return {
      name: data.name,
      poster: tmdb.posterUrl(data.poster_path),
      episodeCount: data.episodes?.length ?? null,
      airDate: data.air_date || null,
    };
  } catch {
    return null;
  }
}

/**
 * The `titles` and `links` column values of one built title, as the API would
 * store them after adding every link of the YAML file by hand. `json` is the
 * title's catalog fragment, built by the API's own `titleEntry`.
 */
export async function titleRows({ entry, detail, data }, createdAt, tmdb, config, now) {
  const isSeries = entry.type === "series";
  const manualPoster = data.poster ?? null;
  let tmdbPoster = entry.poster;
  if (manualPoster) {
    const info = await (isSeries ? tmdb.getTv(entry.tmdb) : tmdb.getMovie(entry.tmdb));
    tmdbPoster = tmdb.posterUrl(info.poster_path);
  }
  const seasons = {};
  if (isSeries) {
    for (const season of new Set(data.links.map((l) => String(l.season)))) {
      if (season === "all") continue;
      const info = await seasonInfo(tmdb, entry.tmdb, season);
      if (info) seasons[season] = info;
    }
  }
  const title = {
    type: entry.type,
    tmdb_id: entry.tmdb,
    imdb: entry.imdb ?? null,
    title: entry.title,
    original_title: entry.originalTitle ?? null,
    english_title: entry.englishTitle ?? null,
    year: entry.year ?? null,
    tmdb_poster: tmdbPoster ?? null,
    poster: manualPoster,
    genres: JSON.stringify(entry.genres),
    seasons: JSON.stringify(seasons),
    season_posters: JSON.stringify(data.seasonPosters ?? {}),
    detail: JSON.stringify(detail),
  };
  const links = data.links.map((l) => ({
    type: entry.type,
    tmdb_id: entry.tmdb,
    season: isSeries ? String(l.season) : null,
    quality: l.quality,
    audio: JSON.stringify(l.audio ?? []),
    subs: JSON.stringify(l.subs ?? []),
    tags: JSON.stringify(l.tags ?? []),
    url: l.link,
    link_key: linkKey(l.link),
    added_by: null,
    created_at: createdAt,
    updated_at: now,
  }));
  title.json = JSON.stringify(titleEntry(title, links.map((l, id) => ({ ...l, id })), config));
  return { title: { ...title, created_at: createdAt, updated_at: now }, links };
}

/** Throws when two files claim the same Telegram message, which the schema forbids. */
function assertUniqueLinks(rows) {
  const seen = new Map();
  for (const { title, links } of rows) {
    for (const { link_key: key } of links) {
      const where = `${title.type}:${title.tmdb_id}`;
      if (seen.has(key)) throw new Error(`${key} is a link of both ${seen.get(key)} and ${where}`);
      seen.set(key, where);
    }
  }
}

/**
 * The SQL that makes a D1 database hold exactly what the YAML files and
 * config say, writing nothing for what already matches. A title whose stored
 * fragment differs gets its links deleted and re-inserted, which keeps their
 * order, and links no file mentions disappear, including the ones added
 * through the API: until the cut-over the YAML files are the source of truth.
 */
export function importSql(rows, config, now) {
  const out = ["-- generated by tools/cositalogo-api/import/import.js; safe to run again"];
  for (const key of ["qualities", "groups", "languages"]) {
    out.push(
      `INSERT INTO settings (key, value) VALUES (${literal(key)}, ${literal(JSON.stringify(config[key]))}) ` +
        `ON CONFLICT (key) DO UPDATE SET value = excluded.value WHERE settings.value IS NOT excluded.value;`
    );
  }
  const sorted = [...rows].sort((a, b) => a.title.type.localeCompare(b.title.type) || a.title.tmdb_id - b.title.tmdb_id);
  for (const { title, links } of sorted) {
    const at = `type = ${literal(title.type)} AND tmdb_id = ${title.tmdb_id}`;
    out.push(`DELETE FROM links WHERE ${at} AND EXISTS (SELECT 1 FROM titles WHERE ${at} AND json IS NOT ${literal(title.json)});`);
    out.push(upsert("titles", "type, tmdb_id", TITLE_COLUMNS, title));
    for (const link of links) {
      out.push(upsert("links", "link_key", LINK_COLUMNS, link));
    }
    out.push(`DELETE FROM links WHERE ${at} AND link_key NOT IN (${links.map((l) => literal(l.link_key)).join(", ")});`);
  }
  for (const type of ["movie", "series"]) {
    const ids = sorted.filter((r) => r.title.type === type).map((r) => r.title.tmdb_id).join(", ");
    out.push(`DELETE FROM links WHERE type = '${type}' AND tmdb_id NOT IN (${ids});`);
    out.push(`DELETE FROM titles WHERE type = '${type}' AND tmdb_id NOT IN (${ids});`);
  }
  out.push(snapshotSql({ onlyIfChanged: true }).replace("?", String(now)) + ";");
  return out.join("\n") + "\n";
}

/** The order scripts/build.js publishes: newest first, then by title. */
function inCatalogOrder(built) {
  return [...built].sort((a, b) => b.addedAt - a.addedAt || a.entry.title.localeCompare(b.entry.title, "es"));
}

/**
 * Builds every title of the YAML files in the working directory and returns
 * the import SQL. The snapshot lists titles by `created_at`, so titles added
 * in the same second (a bulk import is one commit) get distinct values, a few
 * milliseconds apart, that reproduce the build's order.
 */
export async function buildImport({ tmdb, config, addedTimestamps, now }) {
  const built = await loadTitleEntries(
    { tmdb, groups: config.groups, qualities: config.qualities },
    { addedTimestamps, now: Math.floor(now / 1000) }
  );
  const rows = [];
  let previous = Infinity;
  for (const item of inCatalogOrder(built)) {
    const createdAt = Math.min(item.addedAt * 1000, previous - 1);
    previous = createdAt;
    rows.push(await titleRows(item, createdAt, tmdb, config, now));
  }
  assertUniqueLinks(rows);
  return { sql: importSql(rows, config, now), titles: rows.length, links: rows.reduce((n, r) => n + r.links.length, 0) };
}

function addedTimestamps() {
  const output = execFileSync(
    "git",
    ["log", "--no-renames", "--diff-filter=A", "--name-only", "--format=%x00%at"],
    { maxBuffer: 1024 * 1024 * 200 }
  ).toString();
  return parseAddedTimestamps(output);
}

async function main() {
  const args = process.argv.slice(2);
  const option = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
  const out = option("--out", "import.sql");
  const now = Number(option("--now", Date.now()));
  const apiKey = process.env.TMDB_API_KEY;
  if (!apiKey) {
    console.error("TMDB_API_KEY is required for the titles missing from the cache");
    process.exit(1);
  }
  const cachePath = process.env.TMDB_CACHE_PATH ?? ".cache/tmdb.json";
  const cache = loadTmdbCache(cachePath);
  const tmdb = createTmdbClient(apiKey, { cache });
  const result = await buildImport({ tmdb, config: loadConfig(process.cwd()), addedTimestamps: addedTimestamps(), now });
  saveTmdbCache(cachePath, cache);
  writeFileSync(out, result.sql);
  console.log(`import: wrote ${result.titles} titles and ${result.links} links to ${out}`);
}

