import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { isEntrypoint } from "../../../scripts/lib.js";
import { literal } from "../import/import.js";
import { snapshotSql, titleEntry } from "../src/catalog.js";
import { AUDIT_JSON, DIRECTORIES, LINK_JSON, SINGLE_FILES, TITLE_JSON, stringifyColumns } from "./format.js";

/** The backup files under `dir`, as `exportBackup` returns them. */
export function readBackup(dir) {
  const files = new Map();
  const walk = (relative) => {
    for (const entry of readdirSync(join(dir, relative), { withFileTypes: true })) {
      const path = `${relative}/${entry.name}`;
      if (entry.isDirectory()) walk(path);
      else if (entry.name.endsWith(".json")) files.set(path, readFileSync(join(dir, path), "utf8"));
    }
  };
  for (const name of DIRECTORIES) if (existsSync(join(dir, name))) walk(name);
  for (const name of SINGLE_FILES) files.set(name, readFileSync(join(dir, name), "utf8"));
  return files;
}

const insert = (table, row) =>
  `INSERT INTO ${table} (${Object.keys(row).join(", ")}) VALUES (${Object.values(row).map(literal).join(", ")});`;

/**
 * The SQL that replaces the contents of a D1 database with a backup: titles,
 * links, settings, admins, members and audit, with each title's catalog
 * fragment and the snapshot rebuilt as the API would. Login requests and
 * password failures are not backed up and are left as they are.
 */
export function restoreSql(files, now) {
  const settings = JSON.parse(files.get("settings.json"));
  const out = ["-- generated by tools/cositalogo-api/backup/restore.js; replaces the whole catalog"];
  for (const table of ["links", "titles", "settings", "admins", "members", "audit"]) out.push(`DELETE FROM ${table};`);
  for (const [key, value] of Object.entries(settings)) out.push(insert("settings", { key, value: JSON.stringify(value) }));
  for (const name of ["admins", "members"]) {
    for (const row of JSON.parse(files.get(`${name}.json`))) out.push(insert(name, row));
  }
  const paths = [...files.keys()];
  for (const path of paths.filter((p) => p.startsWith("titles/")).sort()) {
    const backup = JSON.parse(files.get(path));
    const title = stringifyColumns(backup.title, TITLE_JSON);
    const links = backup.links.map((l) => ({ type: title.type, tmdb_id: title.tmdb_id, ...stringifyColumns(l, LINK_JSON) }));
    out.push(insert("titles", { ...title, json: JSON.stringify(titleEntry(title, links, settings)) }));
    for (const link of links) out.push(insert("links", link));
  }
  for (const path of paths.filter((p) => p.startsWith("audit/")).sort()) {
    for (const entry of JSON.parse(files.get(path))) out.push(insert("audit", stringifyColumns(entry, AUDIT_JSON)));
  }
  out.push(snapshotSql().replace("?", String(now)) + ";");
  return out.join("\n") + "\n";
}

async function main() {
  const args = process.argv.slice(2);
  const dir = args.find((a) => !a.startsWith("--") && args[args.indexOf(a) - 1] !== "--out");
  const out = args.includes("--out") ? args[args.indexOf("--out") + 1] : "restore.sql";
  if (!dir) {
    console.error("usage: node restore.js <backup directory> [--out restore.sql]");
    process.exit(2);
  }
  writeFileSync(out, restoreSql(readBackup(dir), Date.now()));
  console.log(`restore: wrote ${out}; apply it with wrangler d1 execute <db> --file ${out}`);
}

if (isEntrypoint(import.meta.url)) {
  await main();
}
